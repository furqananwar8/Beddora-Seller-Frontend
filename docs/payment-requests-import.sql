-- cost center helpers (codes follow the app: CID# + level letter + number on that level)
CREATE FUNCTION pg_temp.cc_make(p_name text, p_level int, p_parent int, p_actor int) RETURNS int LANGUAGE plpgsql AS $f$
DECLARE v_seq int; v_code text; v_root int; v_id int;
BEGIN
  SELECT coalesce(max(seq), 0) + 1 INTO v_seq FROM cost_centers WHERE level = p_level;
  SELECT code, coalesce("rootId", id) INTO v_code, v_root FROM cost_centers WHERE id = p_parent;
  INSERT INTO cost_centers (code, name, level, seq, "parentId", "rootId", "createdById", "updatedAt")
  VALUES (coalesce(v_code, 'CID#') || chr(64 + p_level) || v_seq, p_name, p_level, v_seq, p_parent, v_root, p_actor, now()) RETURNING id INTO v_id;
  IF p_level = 1 THEN UPDATE cost_centers SET "rootId" = id WHERE id = v_id; END IF;
  RETURN v_id;
END $f$;

DO $import$
DECLARE
  actor_id int := (SELECT id FROM actor);
  r record; pp record; v_id int; v_l1 int; v_l2 int; v_l3 int; v_req int; v_doc int; v_part int; v_po int; v_mkt int; v_bank int;
  v_total numeric; v_paid numeric; v_bal numeric; v_status text; v_type text; v_due date; v_term int; v_fx numeric; v_base numeric;
  n_req int := 0; n_skip int := 0; n_pop int := 0; n_vendor int := 0; n_cc int := 0; n_nopo int := 0;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM users WHERE id = actor_id) THEN RAISE EXCEPTION 'actor id % is not a user', actor_id; END IF;

  -- 1. Vendor partners: create the ones that are missing (matched by name, ignoring case and extra spaces)
  FOR r IN SELECT * FROM imp_vendor v WHERE NOT EXISTS (SELECT 1 FROM partners p WHERE lower(regexp_replace(trim(p.name), '[[:space:]]+', ' ', 'g')) = lower(v.name)) LOOP
    INSERT INTO partners (name, type, currency, "isActive", "createdById", "updatedAt") VALUES (r.name, 'VENDOR', r.currency, true, actor_id, now());
    n_vendor := n_vendor + 1;
  END LOOP;

  -- 2. L4 expenses: use the existing one by name, else create it under a dummy L3 head ('Imported - to reassign')
  CREATE TEMP TABLE cc_map (name text, id int) ON COMMIT DROP;
  FOR r IN SELECT DISTINCT expense FROM imp_line LOOP
    SELECT id INTO v_id FROM cost_centers WHERE level = 4 AND "isActive" AND lower(trim(name)) = lower(trim(r.expense)) ORDER BY id LIMIT 1;
    IF v_id IS NULL THEN
      SELECT id INTO v_l1 FROM cost_centers WHERE level = 1 AND "isActive" AND name = 'Imported - to reassign' ORDER BY id LIMIT 1;
      IF v_l1 IS NULL THEN v_l1 := pg_temp.cc_make('Imported - to reassign', 1, NULL, actor_id); END IF;
      SELECT id INTO v_l2 FROM cost_centers WHERE level = 2 AND "isActive" AND name = 'Imported - to reassign' AND "parentId" = v_l1 ORDER BY id LIMIT 1;
      IF v_l2 IS NULL THEN v_l2 := pg_temp.cc_make('Imported - to reassign', 2, v_l1, actor_id); END IF;
      SELECT id INTO v_l3 FROM cost_centers WHERE level = 3 AND "isActive" AND name = 'Imported - to reassign' AND "parentId" = v_l2 ORDER BY id LIMIT 1;
      IF v_l3 IS NULL THEN v_l3 := pg_temp.cc_make('Imported - to reassign', 3, v_l2, actor_id); END IF;
      v_id := pg_temp.cc_make(trim(r.expense), 4, v_l3, actor_id);
      n_cc := n_cc + 1;
    END IF;
    INSERT INTO cc_map VALUES (r.expense, v_id);
    v_id := NULL;
  END LOOP;

  -- 3. Requests
  FOR r IN SELECT * FROM imp_req ORDER BY kind DESC, key LOOP
    IF EXISTS (SELECT 1 FROM payment_request_events e WHERE e.type = 'CREATED' AND e.payload ->> 'importKey' = r.key) THEN n_skip := n_skip + 1; CONTINUE; END IF;
    v_po := NULL; v_part := NULL;
    IF r.kind = 'PO' THEN
      SELECT id, "supplierId" INTO v_po, v_part FROM po_orders WHERE "externalRef" = r.po_key ORDER BY id LIMIT 1;
      IF v_po IS NULL THEN RAISE NOTICE 'PO % is not in the database: skipped', r.po_key; n_nopo := n_nopo + 1; CONTINUE; END IF;
    ELSE
      SELECT id INTO v_part FROM partners p WHERE lower(regexp_replace(trim(p.name), '[[:space:]]+', ' ', 'g')) = lower(r.partner) ORDER BY id LIMIT 1;
    END IF;
    SELECT "paymentTermDays" INTO v_term FROM partners WHERE id = v_part;
    SELECT id INTO v_mkt FROM marketplaces WHERE upper(code) = r.dest ORDER BY id LIMIT 1;
    SELECT sum(amount) INTO v_total FROM imp_line WHERE key = r.key;
    v_due := CASE WHEN v_term IS NOT NULL THEN coalesce(r.inv_date, current_date) + v_term END;

    INSERT INTO payment_requests ("partnerId", "referenceType", "invoiceNo", "purchaseOrderId", "invoiceDate", "dueDate", "containerNo", "marketplaceId", "costCenterId",
      currency, amount, "gstType", "gstAmount", "totalAmount", "baseCurrency", "fxRate", "fxRateAsOf", "baseAmount", remarks, status, "requestedById", "submittedAt", "decidedById", "decidedAt", "decisionNote", "updatedAt")
    VALUES (v_part, CASE r.kind WHEN 'PO' THEN 'PURCHASE_ORDER' ELSE 'INVOICE' END::"PaymentReferenceType", NULLIF(r.invoice_no, ''), v_po, coalesce(r.inv_date, current_date), v_due, NULLIF(r.container, ''), v_mkt,
      (SELECT m.id FROM imp_line l JOIN cc_map m ON m.name = l.expense WHERE l.key = r.key ORDER BY l.seq LIMIT 1),
      r.currency, v_total, 'NOT_APPLICABLE', 0, v_total, 'CAD',
      CASE WHEN r.currency = 'CAD' THEN 1 END, CASE WHEN r.currency = 'CAD' THEN coalesce(r.inv_date, current_date) END, CASE WHEN r.currency = 'CAD' THEN v_total END,
      'Imported from PO_Logistic_Combined_with_Payments_v2.xlsx', 'APPROVED', actor_id, now(), actor_id, now(), 'Imported', now())
    RETURNING id INTO v_req;

    INSERT INTO payment_request_lines ("requestId", "costCenterId", amount, "gstAmount", "sortOrder")
    SELECT v_req, m.id, l.amount, 0, l.seq FROM imp_line l JOIN cc_map m ON m.name = l.expense WHERE l.key = r.key ORDER BY l.seq;

    INSERT INTO payment_request_events ("requestId", type, "actorId", payload) VALUES
      (v_req, 'CREATED', actor_id, jsonb_build_object('importKey', r.key)),
      (v_req, 'SUBMITTED', actor_id, NULL),
      (v_req, 'APPROVED', actor_id, jsonb_build_object('note', 'Imported'));

    INSERT INTO payment_documents ("requestId", currency, amount, "updatedAt") VALUES (v_req, r.currency, v_total, now()) RETURNING id INTO v_doc;

    IF r.kind = 'PO' THEN
      -- the tracker's total paid, as one full payment; no payment date is known so no pop is recorded
      UPDATE payment_documents SET "paidAmount" = v_total, status = 'PAID', "markedPaidById" = actor_id, "updatedAt" = now() WHERE id = v_doc;
      INSERT INTO payment_request_events ("requestId", type, "actorId", payload)
      VALUES (v_req, 'PAID', actor_id, jsonb_build_object('status', 'PAID', 'currency', r.currency, 'amount', v_total, 'paidAmount', v_total, 'balance', 0));
    ELSE
      v_paid := 0;
      FOR pp IN SELECT * FROM imp_pop WHERE key = r.key ORDER BY seq LOOP
        SELECT id INTO v_bank FROM bank_profiles WHERE "isActive" AND type = 'BANK' AND currency = pp.bank_ccy ORDER BY id LIMIT 1;
        IF v_bank IS NULL THEN RAISE EXCEPTION 'No active BANK profile in %: add one before importing payments', pp.bank_ccy; END IF;
        v_bal := round(v_total - v_paid, 2);
        v_type := CASE WHEN pp.amount = v_bal THEN 'FULL' ELSE 'SPLIT' END;
        INSERT INTO payment_pops ("paymentDocumentId", type, amount, currency, "paymentDate", "baseCurrency", "fxRateApplied", "baseAmount", "bankProfileId", "processedById")
        VALUES (v_doc, v_type::"PopType", pp.amount, r.currency, pp.pay_date, pp.bank_ccy, pp.rate, pp.base_amount, v_bank, actor_id);
        v_paid := round(v_paid + pp.amount, 2);
        v_status := CASE WHEN round(v_total - v_paid, 2) = 0 THEN 'PAID' ELSE 'PARTIALLY_PAID' END;
        UPDATE payment_documents SET "paidAmount" = v_paid, status = v_status::"PaymentDocStatus", "markedPaidById" = CASE WHEN v_status = 'PAID' THEN actor_id END,
          "markedPaidAt" = CASE WHEN v_status = 'PAID' THEN pp.pay_date::timestamp END, "updatedAt" = now() WHERE id = v_doc;
        INSERT INTO payment_request_events ("requestId", type, "actorId", payload) VALUES (v_req, 'POP_ADDED', actor_id, jsonb_build_object('documentId', v_doc, 'amount', pp.amount, 'currency', r.currency, 'remaining', round(v_total - v_paid, 2)));
        IF v_status = 'PAID' THEN
          INSERT INTO payment_request_events ("requestId", type, "actorId", payload) VALUES (v_req, 'PAID', actor_id, jsonb_build_object('status', 'PAID', 'currency', r.currency, 'amount', v_total, 'paidAmount', v_paid, 'balance', 0));
        END IF;
        n_pop := n_pop + 1;
      END LOOP;
      -- reporting snapshot of a paid USD request: the rate it was actually paid at
      IF r.currency <> 'CAD' AND v_paid > 0 THEN
        UPDATE payment_requests SET "fxRate" = (SELECT round(sum(base_amount) / sum(amount), 8) FROM imp_pop WHERE key = r.key),
          "fxRateAsOf" = (SELECT max(pay_date) FROM imp_pop WHERE key = r.key), "baseAmount" = (SELECT sum(base_amount) FROM imp_pop WHERE key = r.key) WHERE id = v_req;
      END IF;
    END IF;
    n_req := n_req + 1;
  END LOOP;

  RAISE NOTICE 'Created % requests (% already present, % POs missing), % payments, % new vendors, % new L4 expenses.', n_req, n_skip, n_nopo, n_pop, n_vendor, n_cc;
END
$import$;

